CREATE TABLE Skills (
    SkillID BIGINT IDENTITY(1,1) PRIMARY KEY,
    CategoryID BIGINT NOT NULL,
    SkillName NVARCHAR(100) NOT NULL,
    ProficiencyPercentage INT NOT NULL DEFAULT 0,
