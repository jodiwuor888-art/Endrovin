CREATE TABLE ProjectImages (
    ImageID BIGINT IDENTITY(1,1) PRIMARY KEY,
    ProjectID BIGINT NOT NULL,
    ImageUrl NVARCHAR(500) NOT NULL,
    Caption NVARCHAR(255) NULL,
    DisplayOrder INT NOT NULL DEFAULT 0,
